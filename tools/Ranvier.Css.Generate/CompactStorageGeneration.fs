namespace Ranvier.Css.Spec

open System.Text
open System.Text.Json

/// <summary>Generated storage declarations and the category factory name for every grammar node.</summary>
type internal StorageOutput =
    {
        Source: string
        TypeNames: Map<int, string>
    }

/// <summary>Emits hidden grammar contracts and category factories retaining each value's runtime identity.</summary>
module internal CompactStorageGeneration =
    let private quotedName (value: string) =
        "``" + value.Replace ("`", "_") + "``"

    /// <summary>Returns deterministic F# source with one interface object factory per requested admission category.</summary>
    let render (namespaceName: string) (graph: GrammarGraph) (categories: CompactCategories) : StorageOutput =
        let source = StringBuilder ()

        let line (value: string) =
            source.Append(value).Append('\n') |> ignore

        let hidden indent =
            line (
                indent
                + "[<System.ComponentModel.EditorBrowsable(System.ComponentModel.EditorBrowsableState.Never)>]"
            )

        let runtime = "global.Ranvier.Css.Internal.GrammarRuntime"

        let namespacePath =
            namespaceName.Split ('.')
            |> Array.map quotedName
            |> String.concat "."

        line "// <auto-generated />"
        line ("namespace " + namespacePath)
        line ""
        line "/// <summary>Specification grammar storage used by generated CSS value factories.</summary>"
        hidden ""
        line "module CssGrammar ="

        line (
            "    let internal table = "
            + runtime
            + ".Table.decode "
            + JsonSerializer.Serialize graph.Encoded
        )

        line "    /// <summary>Serialized CSS tokens and their validated grammar identity.</summary>"
        hidden "    "
        line "    type IValue ="
        line "        /// <summary>Retains numeric token metadata and the source grammar node.</summary>"
        line ("        abstract Data: " + runtime + ".ValueData")

        for representative in categories.Representatives do
            line "    /// <summary>Values admitted by this specification grammar category.</summary>"
            hidden "    "
            line ("    type C" + string representative + " =")

            match
                Map.tryFind representative categories.Parents
                |> Option.defaultValue []
            with
            | [] -> line "        inherit IValue"
            | parents ->
                for parent in parents do
                    line ("        inherit C" + string parent)

        for representative in categories.Representatives do
            line (
                "    let internal makeC"
                + string representative
                + " (data: "
                + runtime
                + ".ValueData) : C"
                + string representative
                + " ="
            )

            line (
                "        { new C"
                + string representative
                + " with member _.Data = data }"
            )

        let names =
            categories.Categories
            |> Map.toList
            |> List.map (fun (nodeId, representative) ->
                nodeId,
                "global."
                + namespacePath
                + ".CssGrammar.makeC"
                + string representative)
            |> Map.ofList

        {
            Source = source.ToString ()
            TypeNames = names
        }
